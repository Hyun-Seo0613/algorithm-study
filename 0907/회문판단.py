string1 = "JAEZNNZEAJ"
N = 10

# 회문인지 판단하는 방법
# 맨앞/ 맨뒤 같은지 비교
# 맨앞 + 1/ 맨뒤 - 1 같은지 비교
# ...
# 문자열 길이/2 만큼 반복
# 중간에 다른적이 한번이라도 있다면? => 회문이 아니다.

# 회문이라고 가정하고 시작
answer = True

# range에는 정수만 들어감 => / 사용 안됨
# 비교를 N//2만큼, 비교 횟수를 k라고 하자.
for k in range(N//2):
    # k를 이용해서 앞쪽 인덱스, 뒤쪽 인덱스 나타내보기
    # 앞쪽 인덱스는 비교하면서 +1씩 증가
    # 뒤쪽 인덱스는 비교하면서 -1씩 감소
    # 앞쪽과 뒤쪽이 다르면
    # if 앞쪽 != 뒤쪽:
    #     회문이 아니다
    if string1[k] != string1[N-1-k]:
        # 회문이 아님
        answer = False

print(answer)




